//! Sinclair ZX81 (1981) — Z80A + 8 KB ROM + ULA with NMI-driven display.
//!
//! Fresh-write against the workspace pin-driven bus pattern (RULES.md
//! rule 6). Donor at `Emu198x-Oldest/crates/machine-sinclair-zx81/`
//! used the deprecated `emu_core::Bus` callback; this file uses it as
//! the system spec but wires [`emu198x_zilog_z80::Z80`] through its public pin
//! fields and `bus_request()` collapse. The keyboard matrix is shared
//! with the ZX80 — see [`sinclair_zx81_ula`]; the display is not, and
//! [`video`] says why.
//!
//! # The ZX81
//!
//! Sinclair's £49.95 follow-up to the ZX80 (1981). Around 1.5 million
//! units sold worldwide. The display is generated by the processor:
//! the ULA raises NMI once a scan line, the ROM's handler executes a
//! `HALT`, and the CPU then runs *through the display file* while the
//! ULA forces each byte to a `NOP` and shifts the character it names
//! out to the screen. There is no video RAM and no frame buffer. See
//! [`video`] for the mechanism and what settles each part of it.
//!
//! - **CPU:** Zilog Z80A at 3.25 MHz
//! - **ROM:** 8 KB at `$0000-$1FFF` (mirrored to `$2000-$3FFF` and
//!   `$8000-$BFFF`)
//! - **RAM:** 1 KB at `$4000-$43FF` (or 16 KB with the RAM pack);
//!   mirrored to `$C000-$FFFF`
//! - **Display:** 32 × 24 characters, generated by the CPU executing
//!   the display file with the ULA reading the bus
//! - **Audio:** none
//! - **Keyboard:** identical 8 × 5 matrix to the Spectrum / ZX80
//!
//! # NMI generator control
//!
//! Per the donor: OUT to an even port (e.g. `$FE`) enables the NMI
//! generator; OUT to a port with bit 1 clear (e.g. `$FD`) disables it.
//! ROM uses OUT($FD)/OUT($FE).

pub mod input;
mod keyboard;
pub mod video;

pub use input::Zx81Key;
