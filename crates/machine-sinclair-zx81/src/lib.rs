#[cfg(test)]
mod tests {
    use super::*;

    fn trap_rom() -> Vec<u8> {
        let mut rom = vec![0u8; 0x2000];
        rom[0] = 0xF3;
        rom[1] = 0x76;
        rom
    }

    #[test]
    fn frame_advances_master_clock_and_count() {
        let mut sys = Zx81::new(trap_rom(), 1024).expect("init");
        let clocks = sys.run_frame();
        assert!(clocks > 0);
        assert_eq!(sys.frame_count(), 1);
    }

    #[test]
    fn rom_size_validated() {
        assert!(Zx81::new(vec![0u8; 4096], 1024).is_err());
    }

    #[test]
    fn ram_mirrors_at_c000() {
        let mut sys = Zx81::new(trap_rom(), 1024).expect("init");
        sys.mem_write(0x4000, 0x42);
        assert_eq!(sys.mem_read(0xC000), 0x42);
    }

    #[test]
    fn nmi_enabled_toggles_via_io() {
        let mut sys = Zx81::new(trap_rom(), 1024).expect("init");
        assert!(!sys.nmi_enabled());
        sys.io_write(0x00FE, 0);
        assert!(sys.nmi_enabled());
        sys.io_write(0x00FD, 0);
        assert!(!sys.nmi_enabled());
    }

    #[test]
    fn keyboard_press_release() {
        let mut sys = Zx81::new(trap_rom(), 1024).expect("init");
        sys.press_key(Zx81Key::A);
        assert_eq!(sys.io_read(0xFDFE) & 0x01, 0x00);
        sys.release_key(Zx81Key::A);
        assert_eq!(sys.io_read(0xFDFE) & 0x01, 0x01);
    }

    #[test]
    fn snapshot_round_trips_live_state() {
        let mut sys = Zx81::new(trap_rom(), 1024).expect("init");
        sys.run_frame();

        // Write a RAM byte so the captured state is non-trivial. RAM is at
        // $4000+ on the ZX81; confirm the write landed via the read path.
        sys.poke(0x4000, 0x5A);
        assert_eq!(sys.peek(0x4000), 0x5A);

        let first = postcard::to_allocvec(&sys).expect("encode first");

        // Advance and re-serialise — the master clock / frame count move on,
        // so the two snapshots must differ.
        sys.run_frame();
        let second = postcard::to_allocvec(&sys).expect("encode second");
        assert_ne!(first, second, "advancing a frame must change the snapshot");

        // Restoring the first snapshot and re-encoding must be byte-identical.
        let restored: Zx81 = postcard::from_bytes(&first).expect("decode first");
        let reencoded = postcard::to_allocvec(&restored).expect("re-encode restored");
        assert_eq!(first, reencoded, "round-trip must be byte-identical");
    }

    /// The non-keyboard half of the port, bit by bit.
    ///
    /// Bit 5 is not driven and reads high. Bit 6 is the strap and bit 7 the
    /// EAR line — which bit is which was settled against the shipped ROM, see
    /// `zx81_margin_follows_bit_6` in `tests/rom_boot.rs`.
    #[test]
    fn the_port_upper_bits_carry_the_strap_and_the_ear_line() {
        let mut machine = Zx81::new(trap_rom(), 1024).expect("machine");

        // No keys pressed, 50 Hz strap, EAR idle high: the historical 0xFF.
        assert_eq!(machine.read_keyboard_port(0x00), 0xFF);

        machine.set_television_standard(TelevisionStandard::SixtyHz);
        assert_eq!(
            machine.read_keyboard_port(0x00),
            0xBF,
            "a 60 Hz strap must pull bit 6 low and touch nothing else",
        );

        machine.set_ear_input(false);
        assert_eq!(
            machine.read_keyboard_port(0x00),
            0x3F,
            "a low EAR line must pull bit 7 low and touch nothing else",
        );

        machine.set_television_standard(TelevisionStandard::FiftyHz);
        assert_eq!(machine.read_keyboard_port(0x00), 0x7F);

        // Bit 5 is never driven low.
        for standard in [TelevisionStandard::FiftyHz, TelevisionStandard::SixtyHz] {
            machine.set_television_standard(standard);
            assert_eq!(machine.read_keyboard_port(0x00) & 0x20, 0x20);
        }
    }

    /// The window follows the board strap, buffer and placement together.
    ///
    /// This is #1119. `FB_HEIGHT` was a plain `const` at 288 for every ZX81,
    /// so a 60 Hz board painted into a PAL-sized buffer while its runtime
    /// declared a 240-line one, and `FIRST_TEXT_LINE` was the 50 Hz figure so
    /// the picture sat high in it as well. Nothing failed: nothing asserted
    /// the NTSC picture at all, and the 50 Hz path the goldens exercise was
    /// right. That is why this asserts the pair rather than the height alone.
    #[test]
    fn the_window_follows_the_board_strap() {
        let mut machine = Zx81::new(trap_rom(), 1024).expect("machine");
        let width = machine.framebuffer_width();

        assert_eq!(
            machine.framebuffer_height(),
            288,
            "a 50 Hz board scans a PAL set"
        );
        assert_eq!(
            machine.text_top(),
            48,
            "and centres 192 lines of text in it"
        );

        machine.set_television_standard(TelevisionStandard::SixtyHz);
        assert_eq!(
            machine.framebuffer_height(),
            240,
            "a 60 Hz board scans an NTSC set"
        );
        assert_eq!(
            machine.text_top(),
            24,
            "and its shorter pad centres the text in that"
        );

        assert_eq!(
            machine.framebuffer().len(),
            (width * 240) as usize,
            "the buffer itself has to be reallocated, or the height is a claim \
             about a buffer that is still the other region's size"
        );

        machine.set_television_standard(TelevisionStandard::FiftyHz);
        assert_eq!(machine.framebuffer_height(), 288, "and back");
        assert_eq!(machine.framebuffer().len(), (width * 288) as usize);
    }

    /// The keyboard bits still work, and the upper bits do not disturb them.
    #[test]
    fn the_strap_does_not_disturb_the_keyboard_bits() {
        let mut machine = Zx81::new(trap_rom(), 1024).expect("machine");
        machine.press_key(Zx81Key::Shift);
        let fifty = machine.read_keyboard_port(0xFE) & 0x1F;

        machine.set_television_standard(TelevisionStandard::SixtyHz);
        machine.set_ear_input(false);
        assert_eq!(machine.read_keyboard_port(0xFE) & 0x1F, fifty);
        assert_ne!(fifty, 0x1F, "Shift should read as a pressed key");
    }
}

/// One captured I/O port access, for the debug trace.
#[derive(Debug, Clone, Copy)]
pub struct IoEvent {
    /// CPU program counter at the time of the access.
    pub pc: u16,
    /// I/O port — the full 16-bit address bus.
    ///
    /// The ZX81 decodes its keyboard on the **high** byte: `IN A,($FE)`
    /// selects the row from `A15`-`A8`, so a trace that kept only the low
    /// byte could not say which row was scanned. Fixed in #926.
    pub port: u16,
    /// Byte written, or byte returned on a read.
    pub value: u8,
    /// `true` for `OUT`, `false` for `IN`.
    pub write: bool,
}

impl Zx81 {
    /// Observe one byte on the bus without side effects.
    #[must_use]
    pub fn peek(&self, addr: u16) -> u8 {
        self.mem_read(addr)
    }

    /// Write one byte through the bus (RAM accepts it; ROM ignores it).
    pub fn poke(&mut self, addr: u16, value: u8) {
        self.mem_write(addr, value);
    }

    /// Start (or restart) the I/O port-access trace.
    pub fn start_io_trace(&mut self) {
        self.io_trace = Some(Vec::new());
    }

    /// Stop tracing and return the captured I/O events.
    pub fn take_io_trace(&mut self) -> Vec<IoEvent> {
        self.io_trace.take().unwrap_or_default()
    }
}
