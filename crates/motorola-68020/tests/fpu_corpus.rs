//! Single-step validation harness for the 68881/2 FPU against a Musashi
//! oracle corpus.
//!
//! The fixtures come from `m68k-test-gen --fp`, which drives Musashi's
//! on-chip 68040 FPU as the reference. Musashi uses generic-Berkeley
//! SoftFloat; our `floatx80` core is now the 68881/2's SOFTFLOAT_68K
//! (re-based on WinUAE's silicon-validated port), so the two diverge on the
//! 68k special-value encodings (created NaN/∞, denormal exponent/retention,
//! NaN propagation). The authoritative FP-value oracle is therefore the
//! WinUAE C-diff (`crates/motorola-68k-common/validation/run_fpsp.sh`); this
//! corpus validates the rest of the instruction path (decode, operand fetch,
//! FPSR CC, integer state) with the known created-value differences
//! normalised in `compare_final`. See `knowledge/decisions/
//! fpu-softfloat-port.md`.
//!
//! Each fixture covers one register-to-register FPgen instruction
//! (FADD/FSUB/FMUL/FDIV/FCMP/FSQRT/FINT/FINTRZ/FMOVE/FABS/FNEG/FTST) with
//! random normalized-finite operands and FPCR = 0 (round-to-nearest,
//! extended precision).
//!
//! What is compared: the eight FP data registers (full 80-bit values),
//! the FPSR condition-code byte (bits 27-24: N/Z/I/NAN), and the integer
//! architectural state the instruction advances (PC, SR, A/D registers).
//! What is deferred: the FPSR exception/accrued bytes and FPIAR — our
//! core carries `TODO(FPSR)` for exception reporting, so those bits are
//! out of scope until that lands.
//!
//! Default corpus root (generated by `m68k-test-gen --cpu 68040 --fp --all`):
//!   `assets/test-suites/m68k-generated/m68040-fpu/v1/`
//! or the in-repo `test-data/m68k-68040-fpu/v1/`. Override with
//! `M68020_FPU_TEST_DATA`.
//!
//! Skipped under normal `cargo test`. Run explicitly with:
//!
//! ```sh
//! cargo test -p motorola-68020 --test fpu_corpus -- --ignored --nocapture
//! ```

