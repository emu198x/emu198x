/// Widen 8-bit OSC3 samples to 12-bit DAC inputs (`sample << 4`).
#[allow(clippy::cast_lossless)]
const fn widen(samples: &[u8; 4096]) -> [u16; 4096] {
    let mut table = [0_u16; 4096];
    let mut i = 0;
    while i < 4096 {
        table[i] = (samples[i] as u16) << 4;
        i += 1;
    }
    table
}

