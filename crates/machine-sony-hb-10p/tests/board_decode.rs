//! Manufacturer PU-37/S3527 wiring, exercised by actual Z80 bus cycles.
use emu198x_zilog_z80::Z80Stepper;
use machine_sony_hb_10p::Msx;
fn guest(program: &[u8]) -> Msx {
    let mut rom = vec![0; 32768];
    rom[..program.len()].copy_from_slice(program);
    let mut machine = Msx::try_new(rom, None).expect("HB-10P");
    for _ in 0..20_000 {
        machine.step_tick();
    }
    assert_eq!(
        usize::from(machine.cpu().regs.pc),
        program.len(),
        "guest reached HALT"
    );
    machine
}
#[test]
fn slot_zero_page_three_and_slot_three_share_the_same_ram() {
    let m = guest(&[
        0xf3, 0x3e, 0x80, 0xd3, 0xab, // DI; configure PPI outputs
        0x3e, 0xc0, 0xd3, 0xa8, // RAM in page 3, BIOS in page 0
        0x3e, 0x3c, 0x32, 0x00, 0xc0, 0x3e, 0x96, 0x32, 0xff, 0xff, 0x3e, 0x00, 0xd3,
        0xa8, // slot 0 page 3 mirror
        0x3a, 0x00, 0xc0, 0x47, 0x3a, 0xff, 0xff, 0x4f, 0x3e, 0x55, 0x32, 0x00, 0xc0, 0x3e, 0xaa,
        0x32, 0xff, 0xff, 0x3e, 0xc0, 0xd3, 0xa8, 0x3a, 0x00, 0xc0, 0x57, 0x3a, 0xff, 0xff, 0x5f,
        0x76,
    ]);
    let r = &m.cpu().regs;
    assert_eq!((r.b(), r.c(), r.d(), r.e()), (0x3c, 0x96, 0x55, 0xaa));
}
#[test]
fn neighbouring_pages_and_cartridge_slots_do_not_gain_the_mirror() {
    let m = guest(&[
        0xf3, 0x3e, 0x80, 0xd3, 0xab, 0x3e, 0xf0, 0xd3, 0xa8, 0x3e, 0x62, 0x32, 0xff, 0xbf, 0x3e,
        0x00, 0xd3, 0xa8, 0x3a, 0xff, 0xbf, 0x47, 0x3e, 0x40, 0xd3, 0xa8, 0x3e, 0x93, 0x32, 0x00,
        0xc0, 0x3a, 0x00, 0xc0, 0x4f, 0x3e, 0x80, 0xd3, 0xa8, 0x3a, 0x00, 0xc0, 0x57, 0x3e, 0xf0,
        0xd3, 0xa8, 0x3a, 0xff, 0xbf, 0x5f, 0x76,
    ]);
    let r = &m.cpu().regs;
    assert_eq!((r.b(), r.c(), r.d(), r.e()), (0xff, 0xff, 0xff, 0x62));
}
#[test]
fn s3527_ignores_a2_on_ppi_and_psg_ports() {
    let m = guest(&[
        0xf3, 0x3e, 0x80, 0xd3, 0xaf, // AB alias: output mode
        0x3e, 0xc0, 0xd3, 0xac, // A8 alias: primary slots
        0xdb, 0xa8, 0x47, 0xdb, 0xac, 0x4f, 0x3e, 0, 0xd3, 0xa8, 0xdb, 0xac, 0x57, 0x3e, 9, 0xd3,
        0xa0, 0x3e, 8, 0xd3, 0xa4, 0x3e, 7, 0xd3, 0xa5, 0xdb, 0xa2, 0x5f, 0xdb, 0xa6, 0x67, 0xdb,
        0xb0, 0x6f, // adjacent block remains open
        0x76,
    ]);
    let r = &m.cpu().regs;
    assert_eq!((r.b(), r.c(), r.d()), (0xc0, 0xc0, 0));
    assert_eq!((r.e(), r.h(), r.l()), (7, 7, 0xff));
}
#[test]
fn vdp_strobes_cover_the_eight_port_block() {
    let mut program = vec![
        0xf3, 0x3e, 0xf4, 0xd3, 0x9d, 0x3e, 0x87, 0xd3, 0x9d, 0x3e, 0, 0xd3, 0x9d, 0x3e, 0x40,
        0xd3, 0x9d, 0x3e, 0x6d, 0xd3, 0x9c,
    ];
    program.extend([0; 32]); // allow the pending VRAM write its real access window
    program.extend([0xdb, 0x9f, 0x47, 0xdb, 0x88, 0x4f, 0x76]);
    let m = guest(&program);
    let v = m.tms9918().expect("fitted VDP family");
    assert_eq!(v.registers()[7], 0xf4);
    assert_eq!(v.vram()[0], 0x6d);
    assert_ne!(m.cpu().regs.b(), 0xff, "status via alias");
    assert_eq!(
        m.cpu().regs.c(),
        0xff,
        "neighbouring block is not a VDP alias"
    );
}
